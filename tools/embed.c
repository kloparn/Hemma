/* tools/embed.c — bake web assets into the binary.
 *
 *   embed OUT.c BASEDIR FILE... [/published/path=FILE ...]
 *
 * Every FILE is published at "/" + its path relative to BASEDIR (or at the
 * explicit path before '='), with a content type from its extension and an
 * ETag (FNV-1a of the bytes). Runs on the build machine only. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *content_type(const char *path) {
    static const struct {
        const char *ext, *type;
    } types[] = {
        {".css", "text/css; charset=utf-8"},
        {".js", "text/javascript; charset=utf-8"},
        {".html", "text/html; charset=utf-8"},
        {".svg", "image/svg+xml"},
        {".png", "image/png"},
        {".ico", "image/x-icon"},
        {".json", "application/json"},
        {".webmanifest", "application/manifest+json"},
        {".woff2", "font/woff2"},
        {".txt", "text/plain; charset=utf-8"},
        {".wasm", "application/wasm"},
        {".apk", "application/vnd.android.package-archive"},
    };
    const char *dot = strrchr(path, '.');
    for (size_t i = 0; dot && i < sizeof types / sizeof types[0]; i++)
        if (strcmp(dot, types[i].ext) == 0) return types[i].type;
    return "application/octet-stream";
}

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: embed OUT.c BASEDIR FILE...\n");
        return 2;
    }
    FILE *out = fopen(argv[1], "wb");
    if (!out) {
        perror(argv[1]);
        return 1;
    }
    size_t baselen = strlen(argv[2]);
    int n = argc - 3;
    fprintf(out, "/* generated by tools/embed.c from web/ - do not edit */\n#include \"assets.h\"\n\n");
    char **paths = calloc((size_t)n + 1, sizeof *paths);
    size_t *lens = calloc((size_t)n + 1, sizeof *lens);
    uint64_t *hashes = calloc((size_t)n + 1, sizeof *hashes);
    for (int i = 0; i < n; i++) {
        const char *file = argv[3 + i];
        const char *eq = file[0] == '/' ? strchr(file, '=') : NULL;
        if (eq) {
            size_t pl = (size_t)(eq - file);
            paths[i] = malloc(pl + 1);
            memcpy(paths[i], file, pl);
            paths[i][pl] = '\0';
            file = eq + 1;
        }
        FILE *f = fopen(file, "rb");
        if (!f) {
            perror(file);
            return 1;
        }
        if (!eq) { /* published path: strip BASEDIR, normalise separators */
            const char *rel = file;
            if (strncmp(file, argv[2], baselen) == 0) rel = file + baselen;
            while (*rel == '/' || *rel == '\\') rel++;
            paths[i] = malloc(strlen(rel) + 2);
            paths[i][0] = '/';
            strcpy(paths[i] + 1, rel);
        }
        for (char *p = paths[i]; *p; p++)
            if (*p == '\\') *p = '/';

        fprintf(out, "static const unsigned char a%d[] = {", i);
        uint64_t h = 14695981039346656037ULL;
        size_t len = 0;
        int c;
        while ((c = fgetc(f)) != EOF) {
            if (len % 24 == 0) fputs("\n    ", out);
            fprintf(out, "%d,", c);
            h = (h ^ (unsigned char)c) * 1099511628211ULL;
            len++;
        }
        fputs("0};\n", out); /* trailing NUL: text assets can be used as C strings */
        fclose(f);
        lens[i] = len;
        hashes[i] = h;
    }
    fprintf(out, "\nconst Asset g_assets[] = {\n");
    for (int i = 0; i < n; i++)
        fprintf(out, "    {\"%s\", \"%s\", a%d, %zu, \"%016llx\"},\n", paths[i], content_type(paths[i]), i, lens[i],
                (unsigned long long)hashes[i]);
    if (n == 0) fprintf(out, "    {0},\n");
    fprintf(out, "};\nconst int g_nassets = %d;\n", n);
    fclose(out);
    return 0;
}
