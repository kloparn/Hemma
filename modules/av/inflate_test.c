/* What zlib packed above, made again here: 700 words picked by an LCG (Node: Math.imul, the same numbers) */
static size_t zlib_text(uint8_t *out) {
    static const char *const words[] = {"subtitle ", "track ", "the ", "Hemma ", "zlib ", "\n", "picture ", "a ", "of ", "Matroska "};
    uint32_t x = 1;
    size_t n = 0;
    for (int i = 0; i < 700; i++) {
        x = x * 1103515245u + 12345u;
        const char *w = words[(x >> 16) % 10];
        memcpy(out + n, w, strlen(w));
        n += strlen(w);
    }
    return n;
}

static size_t zlib_far(uint8_t *out) { /* 900 letters, 31,000 zero bytes, the same 900 letters */
    uint32_t x = 7;
    for (int i = 0; i < 900; i++) {
        x = x * 1103515245u + 12345u;
        out[i] = (uint8_t)('a' + (x >> 16) % 16);
    }
    memset(out + 900, 0, 31000);
    memcpy(out + 31900, out, 900);
    return 32800;
}

static bool unpacks_to(const uint8_t *z, size_t n, const uint8_t *want, size_t want_len) {
    uint8_t *out = NULL;
    size_t cap = 0, len = 99;
    bool ok = inflate_zlib(z, n, &out, &cap, 1 << 20, &len) && out && len == want_len && !memcmp(out, want, len);
    free(out);
    return ok;
}

static bool refused(const uint8_t *z, size_t n) {
    uint8_t *out = NULL;
    size_t cap = 0, len = 99;
    bool ok = inflate_zlib(z, n, &out, &cap, 1 << 20, &len);
    free(out);
    return !ok && len == 0;
}

TEST(inflate_reads_zlibs_own_streams) {
    static uint8_t text[8192], far[32800];
    size_t tn = zlib_text(text);
    CHECK_INT(tn, 3680);
    CHECK_INT(zlib_far(far), 32800);
    CHECK(unpacks_to((const uint8_t *)Z_STORED, sizeof Z_STORED - 1, text, 300));
    CHECK(unpacks_to((const uint8_t *)Z_FIXED, sizeof Z_FIXED - 1, text, tn));
    CHECK(unpacks_to((const uint8_t *)Z_DYNAMIC, sizeof Z_DYNAMIC - 1, text, tn));
    CHECK(unpacks_to((const uint8_t *)Z_MULTI, sizeof Z_MULTI - 1, text, tn));
    CHECK(unpacks_to((const uint8_t *)Z_FAR, sizeof Z_FAR - 1, far, sizeof far));
    CHECK(unpacks_to((const uint8_t *)Z_EMPTY, sizeof Z_EMPTY - 1, text, 0)); /* (and its out points somewhere) */
    /* one buffer for many frames, as mkv.c keeps it: bigger and smaller ones in turn */
    uint8_t *out = NULL;
    size_t cap = 0, len = 0;
    for (int k = 0; k < 3; k++) {
        CHECK(inflate_zlib((const uint8_t *)Z_FAR, sizeof Z_FAR - 1, &out, &cap, 1 << 20, &len));
        CHECK(len == sizeof far && !memcmp(out, far, len));
        CHECK(inflate_zlib((const uint8_t *)Z_STORED, sizeof Z_STORED - 1, &out, &cap, 1 << 20, &len));
        CHECK(len == 300 && !memcmp(out, text, len));
    }
    /* the most it may make: exactly enough, then one byte short */
    CHECK(inflate_zlib((const uint8_t *)Z_DYNAMIC, sizeof Z_DYNAMIC - 1, &out, &cap, tn, &len) && len == tn);
    CHECK(!inflate_zlib((const uint8_t *)Z_FAR, sizeof Z_FAR - 1, &out, &cap, sizeof far - 1, &len) && len == 0);
    free(out);
}

