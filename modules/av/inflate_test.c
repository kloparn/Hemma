/* A fixed block by hand: 'a', then a match of 3 `back` bytes back, the end */
static size_t hand(uint8_t *z, int back, int lensym, const char *want) {
    ZtW w;
    zt_start(&w, z, 64);
    zt_bits(&w, 1, 1), zt_bits(&w, 1, 2);
    zt_sym(&w, 'a');
    zt_sym(&w, lensym);
    zt_code(&w, (uint32_t)(back - 1), 5); /* distance codes 0..3 = 1..4 back, no extra bits */
    zt_sym(&w, 256);
    return zt_end(&w, want, strlen(want));
}

TEST(inflate_refuses_what_isnt_right) {
    uint8_t z[1024];
    CHECK(unpacks_to(z, hand(z, 1, 257, "aaaa"), (const uint8_t *)"aaaa", 4)); /* (the hand-made stream itself is right) */
    CHECK(refused(z, hand(z, 2, 257, "aaaa")));                                 /* 2 back: before the output's start */
    CHECK(refused(z, hand(z, 1, 286, "aaaa")));                                 /* length codes 286 and 287 mean nothing */
    CHECK(refused(z, hand(z, 1, 287, "aaaa")));
    ZtW w; /* distance codes 30 and 31 neither */
    zt_start(&w, z, 64);
    zt_bits(&w, 1, 1), zt_bits(&w, 1, 2);
    zt_sym(&w, 'a'), zt_sym(&w, 257), zt_code(&w, 30, 5), zt_sym(&w, 256);
    CHECK(refused(z, zt_end(&w, "aaaa", 4)));
    zt_start(&w, z, 64); /* block type 3 */
    zt_bits(&w, 1, 1), zt_bits(&w, 3, 2), zt_bits(&w, 0, 13);
    CHECK(refused(z, zt_end(&w, "", 0)));
    zt_start(&w, z, 64); /* a block that isn't the last, and nothing after it */
    zt_bits(&w, 0, 1), zt_bits(&w, 1, 2), zt_sym(&w, 'a'), zt_sym(&w, 256);
    CHECK(refused(z, zt_end(&w, "a", 1)));
    zt_start(&w, z, 64); /* a dynamic block whose code-length code is over-subscribed: three 1-bit codes */
    zt_bits(&w, 1, 1), zt_bits(&w, 2, 2), zt_bits(&w, 0, 5), zt_bits(&w, 0, 5), zt_bits(&w, 0, 4);
    for (int i = 0; i < 4; i++) zt_bits(&w, i < 3 ? 1 : 0, 3);
    zt_bits(&w, 0, 16);
    CHECK(refused(z, zt_end(&w, "", 0)));

    size_t n = sizeof Z_STORED - 1;
    memcpy(z, Z_STORED, n);
    z[5] ^= 1; /* NLEN not LEN's complement */
    CHECK(refused(z, n));
    n = sizeof Z_DYNAMIC - 1;
    memcpy(z, Z_DYNAMIC, n);
    z[n - 1] ^= 0x10; /* the Adler-32 */
    CHECK(refused(z, n));
    memcpy(z, Z_DYNAMIC, n);
    z[0] = 0x77; /* not deflate */
    CHECK(refused(z, n));
    memcpy(z, Z_DYNAMIC, n);
    z[1] ^= 1; /* the header's check */
    CHECK(refused(z, n));
    memcpy(z, Z_DYNAMIC, n);
    z[1] = 0xBB; /* a preset dictionary (0x78BB is a multiple of 31) */
    CHECK(refused(z, n));
    for (size_t cut = 0; cut < sizeof Z_DYNAMIC - 1; cut++) CHECK(refused((const uint8_t *)Z_DYNAMIC, cut));
    for (size_t cut = 0; cut < sizeof Z_STORED - 1; cut++) CHECK(refused((const uint8_t *)Z_STORED, cut));
}

/* Mangled streams and random bytes: answered (yes or no) without reading or writing out of bounds - the debug build's
   UBSan and CI's ASan watch - and never more than the most allowed. */
TEST(inflate_survives_mangled_and_random_input) {
    static uint8_t z[4096];
    uint8_t *out = NULL;
    size_t cap = 0, len;
    uint32_t r = 2463534242u;
    const struct {
        const char *z;
        size_t n;
    } src[] = {{Z_DYNAMIC, sizeof Z_DYNAMIC - 1}, {Z_FAR, sizeof Z_FAR - 1}, {Z_FIXED, sizeof Z_FIXED - 1}, {Z_MULTI, sizeof Z_MULTI - 1}};
    int yes = 0;
    for (int k = 0; k < 6000; k++) {
        r ^= r << 13, r ^= r >> 17, r ^= r << 5;
        size_t n;
        if (k < 4000) { /* a few bits of a real stream flipped */
            n = src[k % 4].n;
            memcpy(z, src[k % 4].z, n);
            for (uint32_t f = 1 + r % 4, q = r; f--; q = q * 1664525u + 1013904223u) z[2 + (q >> 8) % (n - 2)] ^= (uint8_t)(1u << (q >> 4) % 8);
        } else { /* a right header, then anything */
            n = 2 + r % 600;
            z[0] = 0x78, z[1] = 0x9C;
            for (uint32_t i = 2, q = r; i < n; i++) q = q * 1664525u + 1013904223u, z[i] = (uint8_t)(q >> 24);
        }
        size_t max = k % 3 ? 1 << 16 : 2000;
        if (inflate_zlib(z, n, &out, &cap, max, &len)) {
            yes++;
            CHECK(len <= max);
        }
    }
    CHECK(yes < 6000); /* (most of them are damaged) */
    free(out);
}
